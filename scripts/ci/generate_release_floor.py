# The capability vector + the floor comparison
# ---------------------------------------------------------------------------


@dataclass(frozen=True)
class CapabilityVector:
    xfail_total: int
    xfail_by_priority: dict[str, int]  # keys: PRIORITIES ("P0"/"P1"/"P2"); missing key == 0
    unit_tests_passed: int
    fences_passing: tuple[str, ...]  # sorted

    def to_json(self) -> dict[str, Any]:
        return {
            "xfail_total": self.xfail_total,
            "xfail_by_priority": dict(sorted(self.xfail_by_priority.items())),
            "unit_tests_passed": self.unit_tests_passed,
            "fences_passing": list(self.fences_passing),
        }

    @staticmethod
    def from_json(data: dict[str, Any]) -> CapabilityVector:
        return CapabilityVector(
            xfail_total=int(data["xfail_total"]),
            xfail_by_priority={str(k): int(v) for k, v in data["xfail_by_priority"].items()},
            unit_tests_passed=int(data["unit_tests_passed"]),
            fences_passing=tuple(sorted(data["fences_passing"])),
        )


def capability_vector_from_measurements(
    census: dict[str, Any],
    fence_results: Sequence[tuple[str, bool]],
    unit_tests_passed: int,
) -> CapabilityVector:
    per_classification = census.get("per_classification", {})
    xfail_by_priority = {p: int(per_classification.get(p, 0)) for p in PRIORITIES}
    fences_passing = tuple(sorted(name for name, ok in fence_results if ok))
    return CapabilityVector(
        xfail_total=int(census["total"]),
        xfail_by_priority=xfail_by_priority,
        unit_tests_passed=unit_tests_passed,
        fences_passing=fences_passing,
    )


def compare_vectors(candidate: CapabilityVector, baseline: CapabilityVector) -> list[Violation]:
    """The floor check. Pure — no I/O, fully unit-testable with synthetic vectors. Returns an empty
    list iff the candidate is at or above the floor in EVERY dimension."""
    violations: list[Violation] = []

    if candidate.xfail_total > baseline.xfail_total:
        violations.append(
            Violation(
                "xfail-total-regression",
                f"strict-xfail census total increased {baseline.xfail_total} -> "
                f"{candidate.xfail_total} — more unproven properties is a capability regression "
                "(audit §5)",
            )
        )

    for priority in PRIORITIES:
        base_p = baseline.xfail_by_priority.get(priority, 0)
        cand_p = candidate.xfail_by_priority.get(priority, 0)
        if cand_p > base_p:
            violations.append(
                Violation(
                    "xfail-priority-regression",
                    f"{priority}-classified xfail count increased {base_p} -> {cand_p}, checked "
                    "INDEPENDENTLY of xfail_total — this is what stops a P0 regression from hiding "
                    "behind an unrelated total improvement (audit §5's override-hides-a-P0-"
                    "regression hole)",
                )
            )

    if candidate.unit_tests_passed < baseline.unit_tests_passed:
        violations.append(
            Violation(
                "unit-tests-regression",
                f"passing unit-test count dropped {baseline.unit_tests_passed} -> "
                f"{candidate.unit_tests_passed}",
            )
        )

    missing_fences = sorted(set(baseline.fences_passing) - set(candidate.fences_passing))
    for name in missing_fences:
        violations.append(
            Violation(
                "fence-disabled",
                f"{name!r} was passing at the committed floor and is not passing now — a "
                "previously-enabled fence must never silently go dark",
            )
        )

    return violations


# ---------------------------------------------------------------------------
# Non-vacuity self-check — proves compare_vectors() can both FAIL and PASS before it is trusted
# ---------------------------------------------------------------------------


def _vec(
    xfail_total: int, p0: int, p1: int, p2: int, passed: int, fences: tuple[str, ...]
) -> CapabilityVector:
    return CapabilityVector(xfail_total, {"P0": p0, "P1": p1, "P2": p2}, passed, tuple(sorted(fences)))


#: (label, baseline, candidate, expect_at_least_one_violation). The 4 RED scenarios each regress
#: exactly ONE dimension while holding or IMPROVING every other — proving each dimension is gated
#: independently, not just "the vector as a whole looks worse". The P0 scenario is the audit-§5 hole
#: itself: total IMPROVES (10->9) while a P0 sneaks in (0->1); it must still fail.
SELF_CHECK_SCENARIOS: tuple[tuple[str, CapabilityVector, CapabilityVector, bool], ...] = (
    ("RED total-up", _vec(5, 0, 0, 0, 100, ("a", "b")), _vec(6, 0, 0, 0, 100, ("a", "b")), True),
    (
        "RED P0-up-behind-total-improvement",
        _vec(10, 0, 0, 0, 100, ("a", "b")),
        _vec(9, 1, 0, 0, 100, ("a", "b")),
        True,
    ),
    ("RED unit-tests-down", _vec(5, 0, 0, 0, 100, ("a", "b")), _vec(5, 0, 0, 0, 90, ("a", "b")), True),
    ("RED fence-disabled", _vec(5, 0, 0, 0, 100, ("a", "b")), _vec(5, 0, 0, 0, 100, ("a",)), True),
    ("GREEN exact-hold", _vec(5, 0, 0, 0, 100, ("a", "b")), _vec(5, 0, 0, 0, 100, ("a", "b")), False),
    (
        "GREEN genuine-improvement",
        _vec(5, 0, 0, 0, 100, ("a", "b")),
        _vec(4, 0, 0, 0, 110, ("a", "b", "c")),
        False,
    ),
)


def run_self_check() -> list[Violation]:
    violations: list[Violation] = []
    for label, baseline, candidate, expect_violation in SELF_CHECK_SCENARIOS:
        got_violation = bool(compare_vectors(candidate, baseline))
        if got_violation != expect_violation:
            wanted = "FAIL" if expect_violation else "PASS"
            got = "FAILED" if got_violation else "PASSED"
            violations.append(
                Violation(
                    "self-check-vacuous",
                    f"scenario {label!r}: expected compare_vectors to {wanted} but it {got} — the "
                    "comparator is vacuous or broken; refusing to trust any real measurement",
                )
            )
    return violations


# ---------------------------------------------------------------------------
# Baseline document serialization
# ---------------------------------------------------------------------------


def build_floor_document(vector: CapabilityVector) -> dict[str, Any]:
    return {
        "generated_by": "scripts/ci/generate_release_floor.py",
        "semantics": (
            "FLOOR (non-regression), not an exact-match ledger: --check FAILS only when the "
            "candidate vector is BELOW this baseline in some dimension; it PASSES on an exact hold "
            "or a genuine improvement. Ratchet the floor explicitly via --write — up after a real "
            "fix, or down only with deliberate, reviewed intent — never implicitly."
        ),
        "capability_vector": vector.to_json(),
        "sources": {
            "xfail_total / xfail_by_priority": (
                f"{DEFAULT_CENSUS_PATH} ('total', 'per_classification.P0'/'P1'/'P2'); trusted only "
                "once the 'xfail-census-check' fence below proves it is not stale."
            ),
            "unit_tests_passed": (
                "with `--unit-junit <glob>` (what CI uses): sum of `tests - failures - errors - "
                "skipped` over the `unit` job's own `unit-junit-<shard>.xml` reports, from the same "
                "run — the suite is measured once, by the job that owns it. Without the flag "
                "(local runs): final summary line of `<python> -m pytest tests/ -q`, the same "
                "invocation `make test` runs, executed by this script itself. Either way a red "
                "suite — or, in JUnit mode, a missing/unreadable/empty report — aborts the whole "
                "gate before any comparison."
            ),
            "fences_passing": (
                "each name's own script/mode, invoked exactly as its Makefile target does: "
                + "; ".join(f"{s.name} -> {' '.join(s.argv)}" for s in FENCE_REGISTRY)
            ),
        },
    }


def render_floor_json(doc: dict[str, Any]) -> str:
    return json.dumps(doc, indent=2, ensure_ascii=False) + "\n"


