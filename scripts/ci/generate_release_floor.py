#!/usr/bin/env python3
"""CI gate + generator: the release-capability floor (audit §5, W-fillers).

Purpose
-------
Audit §5 names a hole: an override can hide a P0 regression from a release decision when nobody
recomputes "did this candidate actually get worse" against anything but a hand-maintained ledger. This
script closes that hole the same way `scripts/ci/generate_xfail_census.py` closed the xfail-count
drift hole (PLANS.md §0.8 finding W5): make "capability" a GENERATED number, derived at build time
from truths this repo *already* generates, never hand-recounted and pasted into prose.

Composite capability vector
----------------------------
"Capability" here is deliberately a composite of already-generated truths, not a new invented
number:

  - `xfail_total`      — the strict-xfail census TOTAL (`docs/xfail-census.json`, generated by
                          `generate_xfail_census.py`). More strict-xfails = more unproven properties
                          = less capability. Must not INCREASE.
  - `xfail_by_priority` — the census's own `per_classification` breakdown, narrowed to the
                          `AUTOMATABLE_CLASSES` priorities (`P0`/`P1`/`P2`) that census module
                          already reserves for exactly this purpose (today all real xfails are
                          `HUMAN_CEILING_CLASSES`, i.e. every priority bucket is 0 — see that
                          module's own comment). Each priority is compared INDEPENDENTLY of
                          `xfail_total`: this is what stops a P0 regression from hiding behind an
                          unrelated total improvement (e.g. one human-ceiling xfail fixed +1 P0
                          engineering-gap xfail introduced nets a FLAT or IMPROVED total while a
                          real regression slipped in — audit §5's exact "override hides a P0
                          regression" shape). Must not increase, per priority, regardless of total.
  - `unit_tests_passed` — the passing count of the unit suite, obtained in one of TWO modes:
                          * `--unit-junit <glob>` (what CI uses since 22/09/2026): sum of
                            `tests - failures - errors - skipped` over the JUnit reports the
                            `unit` job's 8 shards already publish (`unit-junit-<shard>.xml`).
                            The suite is measured ONCE per run, by the job that owns it; this gate
                            reads the artifact of the SAME run instead of re-running ~50 min of
                            runner time to recompute a number that already exists. The arithmetic
                            is pytest's own: a `<testsuite>`'s `tests` counts every reported case,
                            and `failures`/`errors`/`skipped` (pytest files xfail under `skipped`)
                            are exactly the cases that did not pass — measured identical to the
                            serial summary line on `tests/unit/agents` (2366 == 2366), in serial
                            and under `-n 2 --dist loadfile`.
                          * no flag (local `make release-floor-check`/`--write`): runs
                            `<python> -m pytest tests/ -q` itself (the same invocation `make test`
                            runs) and parses pytest's own final summary line.
                          Both modes are fail-closed in the same way: a red run (any
                          `failed`/`error`), an unparseable summary, a JUnit report that is missing,
                          unreadable or reports zero cases, aborts the whole gate before any
                          comparison is even attempted — neither a broken suite nor an absent
                          artifact may quietly produce a "lower but still passing" floor number, and
                          NOTHING may silently read as 0.
  - `fences_passing`    — which of the repo's already-wired AST/contract fences
                          (`FENCE_REGISTRY` below — the exact same scripts `artifact-validation`'s
                          CI job runs, invoked exactly as their own Makefile targets do) currently
                          exit 0. A previously-passing fence going dark is a capability regression:
                          "the fences must stay enabled" (mission requirement 3) is enforced by
                          requiring the candidate's passing set to be a SUPERSET of the baseline's.

Floor semantics — the deliberate departure from the census's exact-match pattern
----------------------------------------------------------------------------------
`generate_xfail_census.py --check` requires an EXACT match against the committed ledger (any drift,
better or worse, fails) because a census is a ledger — it should always mirror the tree precisely.
A release-capability gate is different in kind: it is a FLOOR, the worst acceptable state, not a
running tally. This script's `--check` therefore FAILS only when the candidate is BELOW the
committed baseline in some dimension, and PASSES on an exact hold OR a genuine improvement — exactly
mission requirement 4 ("fail on a real regression ... pass on genuine improvement or hold"). The
generation/commit MECHANISM still mirrors the census exactly: a pure generator, a `--write` mode that
regenerates the committed artifact (`docs/release-capability-floor.json`), and a `--check` mode (the
CI gate, default) that never mutates anything. Ratcheting the floor — up after a real fix lands, or
down only with deliberate, reviewed intent — is always an explicit `--write` + commit, never implicit.

Non-vacuity self-check
------------------------
Mirrors the AST fences' own "prove the gate can fail" discipline (e.g.
`check_start_process_fence.py`'s `fence_called_in` non-vacuity proof), applied to a comparator instead
of a scanner: before trusting any real measurement, `run_self_check()` feeds `compare_vectors` four
synthetic REGRESSED scenarios (total up; P0 up while total *improves*, the audit-hole shape above;
unit-tests down; a fence going dark) and two synthetic HELD/IMPROVED scenarios, and refuses to
proceed at all if any of the six doesn't produce the expected PASS/FAIL. A defanged comparator (e.g.
a stray `return []`) fails this self-check loudly instead of silently rubber-stamping every candidate.

Fail-closed contract
---------------------
- Any registered fence errors, `docs/xfail-census.json` is missing, or the unit-test measurement is
  red (`--write` mode) -> refuse to write; a baseline must never encode a known-broken measurement.
- The unit-test measurement is red (`--check` mode) -> FAIL immediately, before the floor
  comparison. In `--unit-junit` mode "red" also covers a measurement that never happened: no file
  matched the glob, a file is not parseable JUnit, or a report has zero cases.
- The self-check itself misbehaves -> FAIL immediately, before measuring anything real.
- `--check`: never mutates `docs/release-capability-floor.json`.

Usage
-----
    python scripts/ci/generate_release_floor.py --check     # local gate: re-runs the suite itself
    python scripts/ci/generate_release_floor.py --check --unit-junit 'unit-junit-*.xml'   # CI gate
    python scripts/ci/generate_release_floor.py --write      # regenerate docs/release-capability-floor.json
"""

