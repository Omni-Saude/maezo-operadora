def build_arg_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        prog="generate_release_floor",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        description=(
            "Generate/verify the committed release-capability floor (audit §5): a composite of "
            "the strict-xfail census, its P0/P1/P2 automatable subset, the passing unit-test "
            "count, and the repo's already-wired AST/contract fences. Fail-closed: an unreadable "
            "census, a red unit-test run, or a broken comparator abort BEFORE any floor comparison."
        ),
        epilog=(
            "modes\n"
            "  --check (default)  measure the current tree; FAIL if it is below the committed\n"
            "                     docs/release-capability-floor.json in any dimension.\n"
            "  --write            measure the current tree and overwrite the committed floor\n"
            "                     (refuses to write if any fence is failing or unit tests are red).\n"
        ),
    )
    parser.add_argument("--repo-root", default=str(REPO_ROOT), help="Repository root.")
    parser.add_argument("--floor-path", default=DEFAULT_FLOOR_PATH, help=f"default: {DEFAULT_FLOOR_PATH}")
    parser.add_argument("--census-path", default=DEFAULT_CENSUS_PATH, help=f"default: {DEFAULT_CENSUS_PATH}")
    parser.add_argument(
        "--python",
        default=sys.executable,
        help="Interpreter used for the fence + pytest subprocess measurements (default: sys.executable).",
    )
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--check", action="store_true", help="Verify only (default if neither flag given).")
    mode.add_argument("--write", action="store_true", help="Regenerate and overwrite the committed floor.")
    return parser


def _resolve(repo_root: Path, raw: str) -> Path:
    path = Path(raw)
    return path if path.is_absolute() else repo_root / path


def main(argv: Sequence[str] | None = None) -> int:
    args = build_arg_parser().parse_args(argv)
    repo_root = Path(args.repo_root).resolve()
    floor_path = _resolve(repo_root, args.floor_path)
    census_path = _resolve(repo_root, args.census_path)

    self_check_violations = run_self_check()
    if self_check_violations:
        print("[release-floor] SELF-CHECK FAIL — comparator is vacuous/broken:", file=sys.stderr)
        for v in self_check_violations:
            print(f"  - {v.render()}", file=sys.stderr)
        return 1
    print(
        f"[release-floor] self-check: {len(SELF_CHECK_SCENARIOS)} scenarios "
        "(4 RED + 2 GREEN) behaved as expected (non-vacuity proof)."
    )

    # Fail fast in --check mode: there is nothing to compare against, so skip the ~minute-scale
    # fence + unit-test measurement below entirely rather than pay that cost only to fail anyway.
    if not args.write and not floor_path.is_file():
        print(f"[release-floor] FAIL: {floor_path} does not exist — run with --write", file=sys.stderr)
        return 1

    fence_results = measure_fences(repo_root, args.python)
    for fr in fence_results:
        print(f"[release-floor] fence {fr.name}: {'PASS' if fr.ok else 'FAIL'} (exit {fr.returncode})")
        if not fr.ok:
            print(f"    {fr.stderr_tail}", file=sys.stderr)

    if not census_path.is_file():
        print(f"[release-floor] FAIL: {census_path} not found", file=sys.stderr)
        return 1
    census = json.loads(census_path.read_text(encoding="utf-8"))

    unit_counts, unit_rc, unit_raw = measure_unit_tests(repo_root, args.python)
    print(f"[release-floor] unit tests: {unit_raw!r} (exit {unit_rc})")
    unit_passed, unit_violations = evaluate_unit_tests(unit_counts, unit_rc, unit_raw)
    if unit_violations:
        print("[release-floor] FAIL — unit-test measurement is not trustworthy:", file=sys.stderr)
        for v in unit_violations:
            print(f"  - {v.render()}", file=sys.stderr)
        return 1

    # `unit_passed` is None only together with a non-empty `unit_violations`, which the guard
    # above already returned on — so it is provably an int here. The assert makes that invariant
    # explicit for a reader (and for mypy, should `scripts/` ever enter the type-checked scope),
    # on the fail-closed path of a shipped gate. (GK-1 review note, Train D release-floor.)
    assert unit_passed is not None
    candidate = capability_vector_from_measurements(
        census, [(fr.name, fr.ok) for fr in fence_results], unit_passed
    )

    if args.write:
        failing = [fr for fr in fence_results if not fr.ok]
        if failing:
            print(
                "[release-floor] FAIL: refusing to --write a baseline while a fence is failing:",
                file=sys.stderr,
            )
            for fr in failing:
                print(f"  - {fr.name} exit={fr.returncode}\n    {fr.stderr_tail}", file=sys.stderr)
            return 1
        doc = build_floor_document(candidate)
        floor_path.parent.mkdir(parents=True, exist_ok=True)
        floor_path.write_text(render_floor_json(doc), encoding="utf-8")
        print(f"[release-floor] WRITE: {candidate.to_json()} -> {floor_path}")
        return 0

    # Default (and --check): verify only, never mutate.
    if not floor_path.is_file():
        print(f"[release-floor] FAIL: {floor_path} does not exist — run with --write", file=sys.stderr)
        return 1
    baseline_doc = json.loads(floor_path.read_text(encoding="utf-8"))
    baseline = CapabilityVector.from_json(baseline_doc["capability_vector"])

    reg_violations = compare_vectors(candidate, baseline)
    if reg_violations:
        print(
            "[release-floor] FAIL — candidate is below the committed release-capability floor:",
            file=sys.stderr,
        )
        for v in reg_violations:
            print(f"  - {v.render()}", file=sys.stderr)
        print(f"  baseline:  {baseline.to_json()}", file=sys.stderr)
        print(f"  candidate: {candidate.to_json()}", file=sys.stderr)
        return 1

    print(
        f"[release-floor] PASS: candidate {candidate.to_json()} meets or exceeds floor {baseline.to_json()}"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
