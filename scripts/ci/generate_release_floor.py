# Unit-test pass count (the one vector field with no pre-existing committed artifact)
# ---------------------------------------------------------------------------

#: Matches pytest's own short-summary tokens: "6839 passed", "3 failed", "1 error"/"2 errors",
#: "1 warning"/"3 warnings", "587 skipped", etc. — whatever pytest chooses to render, never a
#: hand-maintained pattern of our own.
_PYTEST_SUMMARY_TOKEN_RE = re.compile(
    r"(?P<count>\d+)\s+(?P<label>passed|failed|skipped|deselected|xfailed|xpassed|errors?|warnings?)"
)


def parse_pytest_summary_line(line: str) -> dict[str, int]:
    """Pure parser: pytest's final `-q` summary line -> {normalized_label: count}. `errors`/`warnings`
    normalize to their singular key so "1 error" and "2 errors" both land on counts["error"]."""
    counts: dict[str, int] = {}
    for match in _PYTEST_SUMMARY_TOKEN_RE.finditer(line):
        label = match.group("label")
        if label in ("errors", "warnings"):
            label = label[:-1]
        counts[label] = counts.get(label, 0) + int(match.group("count"))
    return counts


def evaluate_unit_tests(
    counts: dict[str, int], returncode: int, raw_line: str
) -> tuple[int | None, list[Violation]]:
    """Pure fail-closed decision: a non-zero exit, any `failed`/`error` count, or an unparseable
    summary line all refuse to produce a passed-count — never silently default to 0 or to whatever
    partial count happened to parse, since either would be misreported as a "regression" instead of
    the "measurement is not trustworthy" state it actually is."""
    violations: list[Violation] = []
    if returncode != 0:
        violations.append(
            Violation(
                "unit-tests-red",
                f"pytest exited {returncode} (non-zero) — {raw_line!r}; a red suite cannot produce "
                "a trustworthy capability measurement",
            )
        )
    if counts.get("failed", 0) or counts.get("error", 0):
        violations.append(
            Violation(
                "unit-tests-red",
                f"pytest summary reports failed={counts.get('failed', 0)} "
                f"error={counts.get('error', 0)} — {raw_line!r}",
            )
        )
    passed = counts.get("passed")
    if passed is None:
        violations.append(
            Violation(
                "unit-tests-unparseable",
                f"could not find a 'N passed' token in the pytest summary line: {raw_line!r}",
            )
        )
    if violations:
        return None, violations
    return passed, []


#: CI run 34733483424 measured 4973.97s for the >20k-test suite with coverage,
#: exceeding the obsolete 1800s budget calibrated to 12k tests. Two hours leaves
#: headroom without changing the selector or the fail-closed acceptance contract.
_UNIT_TESTS_TIMEOUT_SECONDS = 7200


def _run_unit_measurement(repo_root: Path, python_exe: str) -> subprocess.CompletedProcess[str]:
    # Reuse the existing owned process-group cleanup, but preserve this lane's exact
    # environment/argv/stdin. The engine runner's _run deliberately changes those.
    command = [python_exe, "-m", "pytest", "tests/", "-q"]
    process: subprocess.Popen[str] | None = None

    def close_spawned_group() -> None:
        if process is not None and process.pid in process_groups._pending_groups:
            process_groups._quiesce_group(process, process.pid)

    with process_groups._spawn_signal_guard(
        close_spawned_group, handlers={signal.SIGTERM: process_groups._signal_handler}
    ) as activate:
        try:
            process = subprocess.Popen(
                command,
                cwd=repo_root,
                stdout=subprocess.PIPE,
                stderr=subprocess.PIPE,
                text=True,
                stdin=subprocess.DEVNULL,
                start_new_session=True,
            )
            process_groups._record_pending(process.pid)
            activate()
            stdout, stderr = process.communicate(timeout=_UNIT_TESTS_TIMEOUT_SECONDS)
            return subprocess.CompletedProcess(command, process.returncode, stdout, stderr)
        finally:
            with process_groups._cleanup_signal_mask():
                close_spawned_group()


class UnitEvidenceError(RuntimeError):
    """Requested diagnostic retention failed; this is not a unit-suite verdict."""


def _create_unit_evidence(repo_root: Path, destination: Path) -> Path:
    try:
        if not destination.is_absolute() or any(
            path.is_symlink() for path in (destination, *destination.parents)
        ):
            raise ValueError("absolute non-symlink evidence destination required")
        destination = destination.resolve()
        if destination.is_relative_to(repo_root.resolve()):
            raise ValueError("unit evidence must be outside checkout")
        destination.mkdir(mode=0o700, exist_ok=False)
        destination.chmod(0o700)
        return destination
    except (OSError, ValueError) as exc:
        raise UnitEvidenceError("unit evidence destination refused") from exc


def _unit_source_identity(repo_root: Path) -> dict[str, Any]:
    # Record actual executing wrapper bytes even if a local checkout is dirty.
    # HEAD/tree never claim custody of uncommitted test or application changes.
    source: dict[str, Any] = {
        "files": {
            str(path): hashlib.sha256(path.read_bytes()).hexdigest()
            for path in (Path(__file__).resolve(), Path(process_groups.__file__).resolve())
        }
    }
    command = ["git", "--no-replace-objects", "-c", "core.fsmonitor=false"]
    try:
        identity = subprocess.run(
            [*command, "rev-parse", "HEAD", "HEAD^{tree}"],
            cwd=repo_root,
            capture_output=True,
            text=True,
            check=True,
            timeout=5,
        ).stdout.splitlines()
        if len(identity) != 2 or any(not re.fullmatch(r"[0-9a-f]{40,64}", item) for item in identity):
            raise ValueError("invalid source identity")
        clean = subprocess.run(
            [*command, "diff", "--quiet", "HEAD", "--"],
            cwd=repo_root,
            stdout=subprocess.DEVNULL,
            stderr=subprocess.DEVNULL,
            timeout=5,
        ).returncode
        if clean not in (0, 1):
            raise ValueError("source status unavailable")
        source.update(head=identity[0], tree=identity[1], tracked_checkout_clean=clean == 0)
    except (OSError, ValueError, subprocess.SubprocessError):
        source["git_identity_available"] = False
    return source


def _write_unit_evidence(
    destination: Path,
    metadata: dict[str, Any],
    stdout: str | bytes | None,
    stderr: str | bytes | None,
) -> None:
    def encoded(value: str | bytes | None) -> bytes:
        return value if isinstance(value, bytes) else (value or "").encode("utf-8")

    streams = {"stdout.txt": encoded(stdout), "stderr.txt": encoded(stderr)}
    metadata["streams"] = {
        name: {"bytes": len(raw), "sha256": hashlib.sha256(raw).hexdigest()} for name, raw in streams.items()
    }
    # Metadata is last: a partial write cannot masquerade as a complete packet.
    streams["measurement.json"] = (json.dumps(metadata, sort_keys=True, indent=2) + "\n").encode()
    for name, raw in streams.items():
        fd = os.open(destination / name, os.O_WRONLY | os.O_CREAT | os.O_EXCL | os.O_NOFOLLOW, 0o600)
        with os.fdopen(fd, "wb") as output:
            output.write(raw)


def measure_unit_tests(
    repo_root: Path, python_exe: str, *, evidence_dir: Path | None = None
) -> tuple[dict[str, int], int, str]:
    """Measure the unchanged make-test invocation; optionally retain private diagnostics."""
    destination = _create_unit_evidence(repo_root, evidence_dir) if evidence_dir is not None else None
    metadata: dict[str, Any] = {}
    if destination is not None:
        metadata = {
            "argv": [python_exe, "-m", "pytest", "tests/", "-q"],
            "cwd": str(repo_root.resolve()),
            "source_before": _unit_source_identity(repo_root),
            "timeout_seconds": _UNIT_TESTS_TIMEOUT_SECONDS,
        }
    started = time.monotonic()

    def retain(stdout: str | bytes | None, stderr: str | bytes | None, **outcome: Any) -> None:
        if destination is not None:
            metadata.update(
                outcome,
                elapsed_seconds=time.monotonic() - started,
                source_after=_unit_source_identity(repo_root),
                pending_groups=sorted(process_groups._pending_groups),
            )
            _write_unit_evidence(destination, metadata, stdout, stderr)

    try:
        proc = _run_unit_measurement(repo_root, python_exe)
    except BaseException as exc:
        try:
            retain(
                getattr(exc, "stdout", None),
                getattr(exc, "stderr", None),
                returncode=None,
                timed_out=isinstance(exc, subprocess.TimeoutExpired),
                capture_complete=False,
                exception_type=type(exc).__name__,
            )
        except Exception:
            print("[release-floor] unit diagnostic retention failed", file=sys.stderr)
        if isinstance(exc, subprocess.TimeoutExpired):
            raw_line = f"TIMEOUT after {_UNIT_TESTS_TIMEOUT_SECONDS}s running pytest tests/ -q: {exc}"
            return {}, -1, raw_line
        raise
    output_lines = [ln for ln in (proc.stdout + proc.stderr).splitlines() if ln.strip()]
    raw_line = output_lines[-1] if output_lines else ""
    counts = parse_pytest_summary_line(raw_line)
    try:
        retain(proc.stdout, proc.stderr, returncode=proc.returncode, timed_out=False, capture_complete=True)
    except Exception as exc:
        _, violations = evaluate_unit_tests(counts, proc.returncode, raw_line)
        if not violations:
            raise UnitEvidenceError("unit diagnostic retention failed after successful measurement") from exc
        print(
            "[release-floor] unit diagnostic retention failed; original red result preserved", file=sys.stderr
        )
    return counts, proc.returncode, raw_line


# ---------------------------------------------------------------------------
# Unit-test pass count, mode 2: read the shards' JUnit instead of re-running the whole suite
# ---------------------------------------------------------------------------
#
# Why this mode exists (measured, 22/09/2026): the `unit` CI job already runs the ENTIRE unit suite,
# split across 8 shards with xdist, and already publishes `unit-junit-<shard>.xml` as the artifact
# `unit-shard-<shard>` — the same artifact the `quality` job downloads for the coverage gate. This
# gate was running `pytest tests/ -q` a SECOND time, in series, in its own job, purely to fill
# `unit_tests_passed`: ~50 min of runner wall clock per push (22 min already burned when run
# 35727033897 was cancelled). Reading the JUnit of the SAME run measures the same thing the same
# number of times as the suite actually ran — it does not measure less, it stops measuring twice.
#
# What it can NOT do is degrade quietly. A gate whose input is a file is a gate that reads 0 when
# the file is absent, and "0 passed" is >= no floor in the wrong direction only because 0 is a
# NUMBER: it would read as a catastrophic regression on `--check` (harmless) but as a floor of 0 on
# `--write` (a permanently defanged gate). So every not-a-measurement state — glob matched nothing,
# file unreadable/not JUnit, a report with `tests=0` (the shape a collection-time crash leaves),
# any `failures`/`errors` — is a hard violation with its own code, never a count.

#: Matches the `--junitxml=unit-junit-<shard>.xml` the `unit` job's matrix writes, after
#: `actions/download-artifact` with `merge-multiple: true` flattens every `unit-shard-*` into the
#: workspace root — the exact same shape the `quality` job's coverage step consumes.
DEFAULT_UNIT_JUNIT_GLOB = "unit-junit-*.xml"

#: The four `<testsuite>` attributes pytest always writes. `passed` is NOT among them: pytest's
#: JUnit has no such attribute, and `tests` counts every reported case, so the passing count is
#: `tests - failures - errors - skipped`. `skipped` is where pytest files BOTH real skips and
#: xfails (`<skipped type="pytest.xfail">`) — which is exactly right here, because the serial
#: summary line this replaces counts neither as `passed` either.
_JUNIT_COUNT_ATTRIBUTES: tuple[str, ...] = ("tests", "failures", "errors", "skipped")


class JunitParseError(ValueError):
    """A file matched the glob but is not a JUnit report we can trust. Never a verdict on the suite."""


@dataclass(frozen=True)
class JunitCounts:
    """One shard's JUnit report, reduced to the four counts the floor needs."""

    label: str
    tests: int
    failures: int
    errors: int
    skipped: int

    @property
    def passed(self) -> int:
        return self.tests - self.failures - self.errors - self.skipped


def parse_junit_counts(label: str, xml_text: str) -> JunitCounts:
    """Pure parser: one JUnit document -> `JunitCounts`. Sums EVERY `<testsuite>` in the document
    (pytest writes one under a `<testsuites>` root, but a merged/rewritten report may carry several,
    and silently reading only the first would undercount). Raises rather than guessing: a missing or
    non-numeric attribute is an unreadable measurement, not a zero."""
    try:
        root = ElementTree.fromstring(xml_text)
    except ElementTree.ParseError as exc:
        # ElementTree does not expand external entities and raises on undefined ones, so an
        # attacker-supplied XXE payload lands here as a parse error rather than a file read.
        raise JunitParseError(f"{label}: not parseable XML ({exc})") from exc
    suites = list(root.iter("testsuite"))  # includes `root` itself when it IS a <testsuite>
    if not suites:
        raise JunitParseError(f"{label}: no <testsuite> element — not a pytest JUnit report")
    totals = dict.fromkeys(_JUNIT_COUNT_ATTRIBUTES, 0)
    for suite in suites:
        for attribute in _JUNIT_COUNT_ATTRIBUTES:
            raw = suite.get(attribute)
            if raw is None:
                raise JunitParseError(f"{label}: <testsuite> has no {attribute!r} attribute")
            try:
                value = int(raw)
            except ValueError as exc:
                raise JunitParseError(f"{label}: <testsuite> {attribute}={raw!r} is not an integer") from exc
            if value < 0:
                raise JunitParseError(f"{label}: <testsuite> {attribute}={value} is negative")
            totals[attribute] += value
    counts = JunitCounts(label, **totals)
    if counts.passed < 0:
        raise JunitParseError(
            f"{label}: failures+errors+skipped ({counts.tests - counts.passed}) exceeds tests "
            f"({counts.tests}) — incoherent report"
        )
    return counts


def resolve_unit_junit_paths(repo_root: Path, pattern: str) -> list[Path]:
    """Expand the glob (relative to the repo root unless absolute) into a sorted, deterministic file
    list. Sorted so the evidence packet and the printed breakdown never depend on directory order."""
    raw = Path(pattern)
    if raw.is_absolute():
        anchor = Path(raw.anchor)
        matches = anchor.glob(str(raw.relative_to(anchor)))
    else:
        matches = repo_root.glob(pattern)
    return sorted(path for path in matches if path.is_file())


def evaluate_unit_junit(
    reports: Sequence[JunitCounts], read_errors: Sequence[str], pattern: str
) -> tuple[int | None, list[Violation]]:
    """Pure fail-closed decision over already-read reports. Same contract as `evaluate_unit_tests`:
    returns `(None, violations)` for every state that is not a trustworthy measurement, and never a
    partial or zero count."""
    violations: list[Violation] = []
    for message in read_errors:
        violations.append(Violation("unit-junit-unreadable", message))
    if not reports and not read_errors:
        violations.append(
            Violation(
                "unit-junit-missing",
                f"no JUnit report matched {pattern!r} — the unit suite was never measured for this "
                "candidate; an absent artifact must never read as 0 passed",
            )
        )
    for report in reports:
        if report.tests == 0:
            violations.append(
                Violation(
                    "unit-junit-empty",
                    f"{report.label}: reports tests=0 — a shard that collected nothing is a broken "
                    "measurement, not an empty one",
                )
            )
    for report in reports:
        if report.failures or report.errors:
            violations.append(
                Violation(
                    "unit-tests-red",
                    f"{report.label}: failures={report.failures} errors={report.errors} "
                    "(collection errors count here too) — a red suite cannot produce a trustworthy "
                    "capability measurement",
                )
            )
    if violations:
        return None, violations
    total = sum(report.passed for report in reports)
    if total <= 0:
        return None, [
            Violation(
                "unit-junit-empty",
                f"JUnit reports matching {pattern!r} sum to {total} passing tests — refusing to "
                "treat that as a measurement",
            )
        ]
    return total, []


def render_unit_junit_breakdown(reports: Sequence[JunitCounts], pattern: str) -> str:
    lines = [f"pattern: {pattern}"]
    for report in reports:
        lines.append(
            f"{report.label}: tests={report.tests} failures={report.failures} "
            f"errors={report.errors} skipped={report.skipped} passed={report.passed}"
        )
    lines.append(f"TOTAL passed: {sum(report.passed for report in reports)}")
    return "\n".join(lines) + "\n"


def measure_unit_tests_from_junit(
    repo_root: Path, pattern: str, *, evidence_dir: Path | None = None
) -> tuple[int | None, list[Violation], str]:
    """Read the shards' JUnit reports; optionally retain the same private diagnostics packet the
    subprocess mode retains (same directory contract, so the CI upload step is unchanged)."""
    destination = _create_unit_evidence(repo_root, evidence_dir) if evidence_dir is not None else None
    paths = resolve_unit_junit_paths(repo_root, pattern)
    reports: list[JunitCounts] = []
    read_errors: list[str] = []
    file_identity: dict[str, Any] = {}
    for path in paths:
        label = str(path.relative_to(repo_root)) if path.is_relative_to(repo_root) else str(path)
        try:
            raw = path.read_bytes()
        except OSError as exc:
            read_errors.append(f"{label}: cannot be read ({exc})")
            continue
        file_identity[label] = {"bytes": len(raw), "sha256": hashlib.sha256(raw).hexdigest()}
        try:
            reports.append(parse_junit_counts(label, raw.decode("utf-8", errors="replace")))
        except JunitParseError as exc:
            read_errors.append(str(exc))
    passed, violations = evaluate_unit_junit(reports, read_errors, pattern)
    breakdown = render_unit_junit_breakdown(reports, pattern)
    if destination is not None:
        metadata: dict[str, Any] = {
            "mode": "unit-junit",
            "pattern": pattern,
            "cwd": str(repo_root.resolve()),
            "source_after": _unit_source_identity(repo_root),
            "reports": file_identity,
            "counts": [
                {
                    "label": report.label,
                    "tests": report.tests,
                    "failures": report.failures,
                    "errors": report.errors,
                    "skipped": report.skipped,
                    "passed": report.passed,
                }
                for report in reports
            ],
            "unit_tests_passed": passed,
            "violations": [violation.render() for violation in violations],
        }
        try:
            _write_unit_evidence(destination, metadata, breakdown, "\n".join(read_errors))
        except Exception as exc:
            if not violations:
                raise UnitEvidenceError("unit diagnostic retention failed after successful read") from exc
            print(
                "[release-floor] unit diagnostic retention failed; original red result preserved",
                file=sys.stderr,
            )
    return passed, violations, breakdown.strip()


