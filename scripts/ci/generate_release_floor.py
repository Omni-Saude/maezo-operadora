@dataclass(frozen=True)
class FenceSpec:
    """One already-existing CI gate, invoked exactly as its own Makefile target does."""

    name: str
    argv: tuple[str, ...]  # argv[0] is a script path relative to repo root; rest are CLI flags


#: The exact 5 gates `artifact-validation` already runs in `.github/workflows/ci.yml`, named to
#: match their own Makefile targets 1:1 (`check-bpmn-error-allowlist`, `check-start-process-fence`,
#: `effect-chokepoint-fence`, `verify-amh-contract-pin`, `xfail-census-check`). Extending this tuple
#: is a deliberate, reviewed act — the exact same posture `check_start_process_fence.py`'s own
#: `SANCTIONED_RELATIVE_PATHS` takes on its allowlist.
FENCE_REGISTRY: tuple[FenceSpec, ...] = (
    FenceSpec("check-bpmn-error-allowlist", ("scripts/ci/check_bpmn_error_allowlist.py",)),
    FenceSpec("check-start-process-fence", ("scripts/ci/check_start_process_fence.py",)),
    FenceSpec("effect-chokepoint-fence", ("scripts/ci/check_effect_chokepoint_fence.py",)),
    FenceSpec("verify-amh-contract-pin", ("scripts/ci/verify_amh_contract_pin.py",)),
    FenceSpec("xfail-census-check", ("scripts/ci/generate_xfail_census.py", "--check")),
)


@dataclass(frozen=True)
class Violation:
    code: str
    detail: str

    def render(self) -> str:
        return f"[{self.code}] {self.detail}"


@dataclass(frozen=True)
class FenceResult:
    name: str
    ok: bool
    returncode: int
    stderr_tail: str


#: Safety-net bound, not a principal control — every registered fence is AST-only/stdlib-only and
#: finishes in low single-digit seconds on the real tree (measured: <2s each). A hang past this is
#: itself a FAIL, never a silent indefinite block (the fences run inside a CI job with its own
#: outer bound, but a runaway child here must still surface as a loud, attributable failure).
_FENCE_TIMEOUT_SECONDS = 120


def run_fence(repo_root: Path, spec: FenceSpec, python_exe: str) -> FenceResult:
    """Invoke one registered fence as a subprocess. Pure w.r.t. the caller — never raises on a
    non-zero exit or a timeout, that's exactly the signal this function exists to report."""
    script = repo_root / spec.argv[0]
    try:
        proc = subprocess.run(
            [python_exe, str(script), *spec.argv[1:]],
            cwd=repo_root,
            capture_output=True,
            text=True,
            stdin=subprocess.DEVNULL,
            timeout=_FENCE_TIMEOUT_SECONDS,
        )
    except subprocess.TimeoutExpired:
        return FenceResult(spec.name, False, -1, f"TIMEOUT after {_FENCE_TIMEOUT_SECONDS}s — treated as FAIL")
    tail_lines = (proc.stdout + proc.stderr).splitlines()[-5:]
    return FenceResult(spec.name, proc.returncode == 0, proc.returncode, "\n".join(tail_lines))


def measure_fences(repo_root: Path, python_exe: str) -> list[FenceResult]:
    return [run_fence(repo_root, spec, python_exe) for spec in FENCE_REGISTRY]


# ---------------------------------------------------------------------------
# Unit-test pass count (the one vector field with no pre-existing committed artifact)
# ---------------------------------------------------------------------------

#: Matches pytest's own short-summary tokens: "6839 passed", "3 failed", "1 error"/"2 errors",
#: "1 warning"/"3 warnings", "587 skipped", etc. — whatever pytest chooses to render, never a
#: hand-maintained pattern of our own.
_PYTEST_SUMMARY_TOKEN_RE = re.compile(
    r"(?P<count>\d+)\s+(?P<label>passed|failed|skipped|deselected|xfailed|xpassed|errors?|warnings?)"
)


def parse_pytest_summary_line(line: str) -> dict[str, int]:
    """Pure parser: pytest's final `-q` summary line -> {normalized_label: count}. `errors`/`warnings`
    normalize to their singular key so "1 error" and "2 errors" both land on counts["error"]."""
    counts: dict[str, int] = {}
    for match in _PYTEST_SUMMARY_TOKEN_RE.finditer(line):
        label = match.group("label")
        if label in ("errors", "warnings"):
            label = label[:-1]
        counts[label] = counts.get(label, 0) + int(match.group("count"))
    return counts


def evaluate_unit_tests(
    counts: dict[str, int], returncode: int, raw_line: str
) -> tuple[int | None, list[Violation]]:
    """Pure fail-closed decision: a non-zero exit, any `failed`/`error` count, or an unparseable
    summary line all refuse to produce a passed-count — never silently default to 0 or to whatever
    partial count happened to parse, since either would be misreported as a "regression" instead of
    the "measurement is not trustworthy" state it actually is."""
    violations: list[Violation] = []
    if returncode != 0:
        violations.append(
            Violation(
                "unit-tests-red",
                f"pytest exited {returncode} (non-zero) — {raw_line!r}; a red suite cannot produce "
                "a trustworthy capability measurement",
            )
        )
    if counts.get("failed", 0) or counts.get("error", 0):
        violations.append(
            Violation(
                "unit-tests-red",
                f"pytest summary reports failed={counts.get('failed', 0)} "
                f"error={counts.get('error', 0)} — {raw_line!r}",
            )
        )
    passed = counts.get("passed")
    if passed is None:
        violations.append(
            Violation(
                "unit-tests-unparseable",
                f"could not find a 'N passed' token in the pytest summary line: {raw_line!r}",
            )
        )
    if violations:
        return None, violations
    return passed, []


#: Safety-net bound. The suite grew from the historical 40-52s snapshot to 885.98s on the R6
#: floor and 1242.60s on the integrated Fleet candidate (12210 passed, 14 skipped, 662 deselected,
#: 1 xfailed; no assertion failure). 1800s leaves measured CI headroom while remaining a finite,
#: fail-closed subprocess deadline: a timeout still returns rc=-1 and can never satisfy the floor.
_UNIT_TESTS_TIMEOUT_SECONDS = 1800


def unit_failure_witness(output: str, repo_root: Path) -> dict[str, Any]:
    """Bounded source-file groups only: never parameters, tracebacks or exception text."""
    groups: dict[tuple[str, str], int] = {}
    in_summary = False
    unmatched = 0
    root = repo_root.resolve()
    for line in output.splitlines():
        if re.fullmatch(r"=+ short test summary info =+", line.strip()):
            in_summary = True
            continue
        if not in_summary or not line.startswith(("FAILED ", "ERROR ")):
            continue
        match = re.match(r"(FAILED|ERROR) (tests/[A-Za-z0-9_./-]+\.py)(?=::|\s|$)", line)
        if match is None:
            unmatched += 1
            continue
        relative = match.group(2)
        candidate = root / relative
        if (
            ".." in Path(relative).parts
            or not candidate.is_file()
            or not candidate.resolve().is_relative_to(root / "tests")
        ):
            unmatched += 1
            continue
        key = (match.group(1).lower(), relative)
        groups[key] = groups.get(key, 0) + 1
    selected = sorted(groups.items())
    return {
        "short_summary_present": in_summary,
        "file_groups": [
            {"outcome": outcome, "path": path, "reports": count} for (outcome, path), count in selected[:40]
        ],
        "omitted_file_groups": max(0, len(selected) - 40),
        "unmatched_reports": unmatched,
    }


def measure_unit_tests(repo_root: Path, python_exe: str) -> tuple[dict[str, int], int, str]:
    """Runs the SAME invocation `make test` runs (`pytest tests/ -q -m "not integration"`) and returns
    (parsed_counts, returncode, raw_summary_line). Thin I/O wrapper — the fail-closed decision logic
    lives in the pure `evaluate_unit_tests` above so it can be unit-tested without a nested pytest
    subprocess. `stdin=DEVNULL` is deliberate: this subprocess must never be able to block waiting
    on a stdin that was never meant for it."""
    try:
        proc = subprocess.run(
            [python_exe, "-m", "pytest", "tests/", "-q", "-m", "not integration"],
            cwd=repo_root,
            capture_output=True,
            text=True,
            stdin=subprocess.DEVNULL,
            timeout=_UNIT_TESTS_TIMEOUT_SECONDS,
        )
    except subprocess.TimeoutExpired as exc:
        partial = exc.stdout or ""
        if isinstance(partial, bytes):
            partial = partial.decode("utf-8", errors="replace")
        print("[release-floor] unit failure witness: " + json.dumps(unit_failure_witness(partial, repo_root)))
        raw_line = f"TIMEOUT after {_UNIT_TESTS_TIMEOUT_SECONDS}s running unit pytest (not integration)"
        return {}, -1, raw_line
    output = proc.stdout + proc.stderr
    output_lines = [ln for ln in output.splitlines() if ln.strip()]
    raw_line = output_lines[-1] if output_lines else ""
    counts = parse_pytest_summary_line(raw_line)
    if proc.returncode != 0 or counts.get("failed", 0) or counts.get("error", 0) or "passed" not in counts:
        print("[release-floor] unit failure witness: " + json.dumps(unit_failure_witness(output, repo_root)))
    return counts, proc.returncode, raw_line


