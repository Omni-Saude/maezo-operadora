"""Derive readable queue labels from the BPMN `name` of each bound process/userTask.

The label text is never written by hand: it is the `name` attribute the process
designer gave the `<bpmn:process>` and `<bpmn:userTask>` in spec/processes/bpmn,
restricted to the (process, task) pairs the Q1 registry binds to a portal form.
Static design-time names only; no case or person data ever reaches this file.
"""

import json
import sys
from pathlib import Path

source = Path(__file__).resolve().parents[4]
repo = source.parent
sys.path.insert(0, str(source))
from maezo.platform.xml_safe import parse_xml_without_dtd  # noqa: E402
from maezo.portal.contracts import models  # noqa: E402

BPMN = "{http://www.omg.org/spec/BPMN/20100524/MODEL}"


def _clean(name: str) -> str:
    return " ".join(name.split())


def _names() -> tuple[dict[str, str], dict[tuple[str, str], str]]:
    processes: dict[str, str] = {}
    tasks: dict[tuple[str, str], str] = {}
    for path in sorted((repo / "spec/processes/bpmn").glob("*.bpmn")):
        root = parse_xml_without_dtd(path.read_bytes())
        for process in root.iter(f"{BPMN}process"):
            process_id = process.get("id", "")
            name = _clean(process.get("name", ""))
            processes[process_id] = _clean(name.removeprefix(process_id))
            for task in process.iter(f"{BPMN}userTask"):
                tasks[(process_id, task.get("id", ""))] = _clean(task.get("name", ""))
    return processes, tasks


def render() -> str:
    processes, tasks = _names()
    rows = []
    for process, task in sorted(models._BINDINGS):
        process_label = processes.get(process, "")
        task_label = tasks.get((process, task), "")
        if not process_label or not task_label:
            raise SystemExit(f"binding sem nome BPMN: {process}/{task}")
        rows.append(
            {
                "process": process,
                "task": task,
                "processLabel": process_label,
                "taskLabel": task_label,
            }
        )
    return (
        "// Generated by scripts/generate-task-labels.py from the BPMN `name` of each\n"
        "// bound process/userTask (spec/processes/bpmn, pairs from Q1 models.py).\n"
        "// Static design-time names only; never case data. Regenerate, do not edit.\n"
        "export const taskLabels = " + json.dumps(rows, ensure_ascii=False, indent=2) + " as const;\n"
    )


target = Path(__file__).resolve().parents[1] / "src/taskLabels.ts"
if __name__ == "__main__":
    text = render()
    if sys.argv[1:] == ["--check"]:
        if target.read_text(encoding="utf-8") != text:
            raise SystemExit("taskLabels.ts differs from the BPMN names; run generate-task-labels.py")
    elif not sys.argv[1:]:
        target.write_text(text, encoding="utf-8")
    else:
        raise SystemExit("usage: generate-task-labels.py [--check]")
